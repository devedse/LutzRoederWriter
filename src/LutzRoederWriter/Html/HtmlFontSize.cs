using System;

namespace Writer.Html
{
	/// <summary>
	/// Specifies the seven legacy HTML font sizes supported by MSHTML.
	/// </summary>
	public enum HtmlFontSize
	{
		/// <summary>The smallest font size.</summary>
		Smallest = 1,
		/// <summary>A smaller-than-default font size.</summary>
		Smaller,
		/// <summary>A small font size.</summary>
		Small,
		/// <summary>The default font size.</summary>
		Medium,
		/// <summary>A large font size.</summary>
		Large,
		/// <summary>A larger font size.</summary>
		Larger,
		/// <summary>The largest font size.</summary>
		Largest
	}
}
