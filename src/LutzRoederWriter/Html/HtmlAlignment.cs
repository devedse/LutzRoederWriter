using System;

namespace Writer.Html
{
	/// <summary>
	/// Specifies paragraph alignment in the MSHTML editing surface.
	/// </summary>
	public enum HtmlAlignment
	{
		/// <summary>Aligns content to the left.</summary>
		Left,
		/// <summary>Centers content.</summary>
		Center,
		/// <summary>Aligns content to the right.</summary>
		Right,
		/// <summary>Justifies content across the available width.</summary>
		Full
	}
}
